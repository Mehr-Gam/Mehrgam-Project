export const getProvinceOptions = () => [
  { value: '', label: 'انتخاب استان' },
  ...iranProvinces.map((item) => ({ value: item.province, label: item.province })),
]

export const getCityOptions = (province) => {
  const selectedProvince = iranProvinces.find((item) => item.province === province)

  if (!selectedProvince) {
    return [{ value: '', label: 'ابتدا استان را انتخاب کنید' }]
  }

  return [
    { value: '', label: 'انتخاب شهر' },
    ...selectedProvince.cities.map((city) => ({ value: city, label: city })),
  ]
}
